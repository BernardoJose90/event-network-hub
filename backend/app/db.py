"""PostgreSQL persistence for documents and versions (see pg.py for the connection layer)."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from . import pg

STATUS_PROCESSING = "processing"
STATUS_READY = "ready"
STATUS_FAILED = "failed"

SCHEMA = """
CREATE TABLE IF NOT EXISTS documents (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    created_at  TEXT NOT NULL,
    kind        TEXT NOT NULL DEFAULT 'event' CHECK (kind IN ('event', 'template')),
    archived_at TEXT,  -- archived events are read-only and listed separately
    archived_by TEXT
);

CREATE TABLE IF NOT EXISTS document_versions (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    version      INTEGER NOT NULL,
    sha256       TEXT NOT NULL,
    uploaded_by  TEXT NOT NULL,
    uploaded_at  TEXT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('processing', 'ready', 'failed')),
    error        TEXT,
    edited_from  INTEGER,
    source       TEXT NOT NULL DEFAULT 'upload',  -- upload | publish ('edit' from the removed spreadsheet editor)
    UNIQUE (document_id, version)
);

CREATE TABLE IF NOT EXISTS download_log (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id     INTEGER NOT NULL REFERENCES document_versions(id) ON DELETE CASCADE,
    "user"         TEXT NOT NULL,
    format         TEXT NOT NULL DEFAULT 'pdf' CHECK (format IN ('pdf', 'xlsx')),
    downloaded_at  TEXT NOT NULL
);
"""


def utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def connect(database: pg.Database) -> pg.Connection:
    return pg.connect(database)


# Held while creating the schema, so pods starting at the same time don't race each other.
_SCHEMA_LOCK = 4_242_001


def init_db(database: pg.Database) -> None:
    """Create any missing tables. Safe to run on every start-up, from several pods at once."""
    from .ictrequests import service as requests_service
    from .notifications import service as notifications_service
    from .records import comments as records_comments, store as records_store
    from .tickets import store as tickets_store

    conn = connect(database)
    try:
        with conn:
            conn.execute("SELECT pg_advisory_xact_lock(?)", (_SCHEMA_LOCK,))
            conn.executescript(SCHEMA)
            records_store.init(conn)  # records tables reference documents/versions
            records_comments.init(conn)
            tickets_store.init(conn)
            requests_service.init(conn)
            notifications_service.init(conn)
    finally:
        conn.close()


# --- documents --------------------------------------------------------------


def create_document(conn: pg.Connection, name: str) -> dict[str, Any]:
    with conn:
        document_id = insert_document(conn, name)
    return get_document(conn, document_id)  # type: ignore[return-value]


def insert_document(conn: pg.Connection, name: str, kind: str = "event") -> int:
    """Insert a document without committing, for callers that add more in the same transaction.

    kind 'template': an event template, listed only under "Start from", never published.
    """
    return conn.execute(
        "INSERT INTO documents (name, created_at, kind) VALUES (?, ?, ?) RETURNING id", (name, utcnow(), kind)
    ).fetchone()[0]


def get_document(conn: pg.Connection, document_id: int) -> dict[str, Any] | None:
    row = conn.execute("SELECT * FROM documents WHERE id = ?", (document_id,)).fetchone()
    return dict(row) if row else None


def get_document_by_name(conn: pg.Connection, name: str) -> dict[str, Any] | None:
    row = conn.execute("SELECT * FROM documents WHERE name = ?", (name,)).fetchone()
    return dict(row) if row else None


def list_documents(conn: pg.Connection, kind: str = "event") -> list[dict[str, Any]]:
    rows = conn.execute(
        """
        SELECT d.*,
               (SELECT MAX(version) FROM document_versions v
                 WHERE v.document_id = d.id AND v.status = 'ready') AS latest_ready_version
          FROM documents d
         WHERE d.kind = ?
         ORDER BY d.name
        """,
        (kind,),
    ).fetchall()
    docs = [dict(r) | {"versions": []} for r in rows]
    by_id = {d["id"]: d for d in docs}
    # One query for every document's versions, newest first, for the sidebar.
    for v in conn.execute(
        "SELECT document_id, version, status FROM document_versions ORDER BY document_id, version DESC"
    ):
        if v["document_id"] in by_id:
            by_id[v["document_id"]]["versions"].append({"version": v["version"], "status": v["status"]})
    return docs


class EventArchived(Exception):
    """The event is archived, so it can't be changed. ``str(exc)`` is user-facing."""

    def __init__(self, name: str) -> None:
        super().__init__(f"'{name}' is archived and read-only. Restore it to make changes.")


def ensure_not_archived(conn: pg.Connection, document_id: int) -> None:
    """Raise EventArchived if the document is archived (missing documents are the caller's concern)."""
    row = conn.execute("SELECT name, archived_at FROM documents WHERE id = ?", (document_id,)).fetchone()
    if row is not None and row["archived_at"]:
        raise EventArchived(row["name"])


def set_document_archived(conn: pg.Connection, document_id: int, *, user: str | None) -> None:
    """Archive (user given) or restore (user None) a document."""
    with conn:
        conn.execute(
            "UPDATE documents SET archived_at = ?, archived_by = ? WHERE id = ?",
            (utcnow() if user else None, user, document_id),
        )


def delete_document(conn: pg.Connection, document_id: int) -> None:
    """Delete a document; its versions and download log rows go with it (ON DELETE CASCADE)."""
    with conn:
        conn.execute("DELETE FROM documents WHERE id = ?", (document_id,))


# --- versions ---------------------------------------------------------------


def _version(row: pg.Row | None) -> dict[str, Any] | None:
    return dict(row) if row is not None else None


def insert_version(
    conn: pg.Connection,
    *,
    document_id: int,
    version: int,
    sha256: str,
    uploaded_by: str,
    edited_from: int | None = None,
    source: str = "upload",
) -> dict[str, Any]:
    """Insert a version row in 'processing' state.

    Raises pg.IntegrityError if ``version`` is already taken for this document.
    """
    with conn:
        cur = conn.execute(
            """
            INSERT INTO document_versions
                (document_id, version, sha256, uploaded_by, uploaded_at, status, edited_from, source)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            RETURNING id
            """,
            (document_id, version, sha256, uploaded_by, utcnow(), STATUS_PROCESSING, edited_from, source),
        )
    return get_version_by_id(conn, cur.fetchone()[0])  # type: ignore[return-value]


def max_version(conn: pg.Connection, document_id: int) -> int:
    row = conn.execute(
        "SELECT COALESCE(MAX(version), 0) FROM document_versions WHERE document_id = ?", (document_id,)
    ).fetchone()
    return int(row[0])


def delete_version(conn: pg.Connection, version_id: int) -> None:
    with conn:
        conn.execute("DELETE FROM document_versions WHERE id = ?", (version_id,))


def set_version_status(
    conn: pg.Connection, version_id: int, status: str, error: str | None = None
) -> None:
    with conn:
        conn.execute(
            "UPDATE document_versions SET status = ?, error = ? WHERE id = ?",
            (status, error, version_id),
        )


def get_version_by_id(conn: pg.Connection, version_id: int) -> dict[str, Any] | None:
    return _version(
        conn.execute("SELECT * FROM document_versions WHERE id = ?", (version_id,)).fetchone()
    )


def get_version(conn: pg.Connection, document_id: int, version: int) -> dict[str, Any] | None:
    return _version(
        conn.execute(
            "SELECT * FROM document_versions WHERE document_id = ? AND version = ?",
            (document_id, version),
        ).fetchone()
    )


def latest_version(
    conn: pg.Connection, document_id: int, *, statuses: tuple[str, ...]
) -> dict[str, Any] | None:
    placeholders = ",".join("?" for _ in statuses)
    return _version(
        conn.execute(
            f"""
            SELECT * FROM document_versions
             WHERE document_id = ? AND status IN ({placeholders})
             ORDER BY version DESC LIMIT 1
            """,
            (document_id, *statuses),
        ).fetchone()
    )


def list_versions(conn: pg.Connection, document_id: int) -> list[dict[str, Any]]:
    rows = conn.execute(
        "SELECT * FROM document_versions WHERE document_id = ? ORDER BY version DESC",
        (document_id,),
    ).fetchall()
    return [_version(r) for r in rows]  # type: ignore[misc]


# --- download log -----------------------------------------------------------


def log_download(conn: pg.Connection, *, version_id: int, user: str, format: str) -> None:
    with conn:
        conn.execute(
            'INSERT INTO download_log (version_id, "user", format, downloaded_at) VALUES (?, ?, ?, ?)',
            (version_id, user, format, utcnow()),
        )

