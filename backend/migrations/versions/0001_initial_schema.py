"""Initial schema: the 24 tables of the SQLite database, in PostgreSQL.

Revision ID: 0001
Revises:
Created: 2026-10-21

Carried over as they were, so the data copies across unchanged (app/copy_from_sqlite.py):
- timestamps stay ISO 8601 text in UTC ("2026-10-21T09:30:00+00:00"), compared as text;
- JSON stays text, read and written by the app;
- yes/no flags stay 0/1 integers.
Ids are BIGINT identities, GENERATED BY DEFAULT so the copy can keep the SQLite ids.
"user" is a reserved word in PostgreSQL, so that column is always quoted.
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

SCHEMA = """
-- --- documents and versions ---------------------------------------------------------------

CREATE TABLE documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    created_at   TEXT NOT NULL,
    kind         TEXT NOT NULL DEFAULT 'event' CHECK (kind IN ('event', 'template')),
    archived_at  TEXT,  -- archived events are read-only and listed separately
    archived_by  TEXT
);

CREATE TABLE document_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    version      INTEGER NOT NULL,
    sha256       TEXT NOT NULL,
    uploaded_by  TEXT NOT NULL,
    uploaded_at  TEXT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('processing', 'ready', 'failed')),
    error        TEXT,
    edited_from  BIGINT,
    source       TEXT NOT NULL DEFAULT 'upload',  -- upload | publish ('edit' from the removed spreadsheet editor)
    UNIQUE (document_id, version)
);

CREATE TABLE download_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id     BIGINT NOT NULL REFERENCES document_versions(id) ON DELETE CASCADE,
    "user"         TEXT NOT NULL,
    format         TEXT NOT NULL DEFAULT 'pdf' CHECK (format IN ('pdf', 'xlsx')),
    downloaded_at  TEXT NOT NULL
);
CREATE INDEX download_log_by_version ON download_log (version_id);

-- --- event records --------------------------------------------------------------------------

CREATE TABLE event_venues (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    name         TEXT NOT NULL,
    sort         DOUBLE PRECISION NOT NULL,
    UNIQUE (document_id, name)
);

-- Wi-Fi groups (Core Networks, Lounges, ...) and Ethernet sections (INTERNAL WORKSPACES, ...).
CREATE TABLE event_groups (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    kind         TEXT NOT NULL CHECK (kind IN ('wifi', 'ethernet')),
    name         TEXT NOT NULL,
    sort         DOUBLE PRECISION NOT NULL,
    UNIQUE (document_id, kind, name)
);

-- Managed lists (the old Setup sheet). flagged = added by an import, to review.
CREATE TABLE event_lists (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    kind         TEXT NOT NULL CHECK (kind IN ('building', 'location', 'vlan', 'bandwidth')),
    value        TEXT NOT NULL,
    sort         DOUBLE PRECISION NOT NULL,
    flagged      INTEGER NOT NULL DEFAULT 0,
    UNIQUE (document_id, kind, value)
);

CREATE TABLE records (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    type         TEXT NOT NULL CHECK (type IN ('wifi', 'ethernet', 'partner', 'vlan_extension')),
    venue_id     BIGINT REFERENCES event_venues(id) ON DELETE CASCADE,
    group_id     BIGINT REFERENCES event_groups(id) ON DELETE CASCADE,
    sort         DOUBLE PRECISION NOT NULL,
    data         TEXT NOT NULL,
    revision     INTEGER NOT NULL DEFAULT 1,
    updated_by   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    archived_at  TEXT,  -- no longer set (archiving items was replaced by deleting)
    archived_by  TEXT
);
CREATE INDEX records_by_type ON records (document_id, type, venue_id, group_id, sort);

-- Every change, written automatically. action: create, update, delete, move,
-- list, venue, group, import, publish, reveal, legacy (imported old log).
CREATE TABLE change_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    entity       TEXT NOT NULL,
    record_id    BIGINT,
    action       TEXT NOT NULL,
    field        TEXT,
    old          TEXT,
    new          TEXT,
    summary      TEXT NOT NULL,
    "user"       TEXT NOT NULL,
    at           TEXT NOT NULL
);
CREATE INDEX change_log_by_doc ON change_log (document_id, id);

CREATE TABLE published_snapshots (
    version_id   BIGINT PRIMARY KEY REFERENCES document_versions(id) ON DELETE CASCADE,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    data         TEXT NOT NULL
);

-- Item lists read from uploaded or edited workbooks, so every version can be compared.
-- A cache: versions are immutable, and a row can always be rebuilt from the stored file.
CREATE TABLE workbook_snapshots (
    version_id   BIGINT PRIMARY KEY REFERENCES document_versions(id) ON DELETE CASCADE,
    data         TEXT NOT NULL
);

CREATE TABLE comments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    parent_id    BIGINT REFERENCES comments(id) ON DELETE CASCADE,  -- set on replies
    record_id    BIGINT,          -- the item; no foreign key, so comments outlive deleted items
    record_type  TEXT,
    item_label   TEXT,            -- e.g. "Stage 2 - Press", copied when the comment is made
    item_where   TEXT,            -- e.g. "Main venue · STAGES"
    version      INTEGER,         -- latest published version when it was made (NULL = before V1)
    body         TEXT NOT NULL,
    "user"       TEXT NOT NULL,
    role         TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    resolved_at  TEXT,
    resolved_by  TEXT
);
CREATE INDEX comments_by_doc ON comments (document_id, parent_id);

-- --- help desk ---------------------------------------------------------------------------------
-- Tickets are a permanent record: they are never deleted, and they survive the deletion of
-- their event (event_id becomes NULL; event_code is kept).

CREATE TABLE tickets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         BIGINT REFERENCES documents(id) ON DELETE SET NULL,
    event_code       TEXT,
    title            TEXT NOT NULL,
    description      TEXT,
    category         TEXT NOT NULL CHECK (category IN
                       ('wifi', 'wired', 'hardware', 'partner_stand', 'venue', 'uncategorised')),
    severity         TEXT NOT NULL CHECK (severity IN ('P1', 'P2', 'P3', 'P4')),
    status           TEXT NOT NULL CHECK (status IN
                       ('new', 'acknowledged', 'in_progress', 'waiting', 'resolved', 'closed')),
    team             TEXT NOT NULL CHECK (team IN ('network', 'it_support')),
    assignee         TEXT,
    location         TEXT,
    stand            TEXT,
    partner          TEXT,
    reporter_name    TEXT,
    reporter_phone   TEXT,
    source           TEXT NOT NULL CHECK (source IN ('whatsapp', 'manual')),
    external_id      TEXT UNIQUE,  -- the bot's report id: makes bot retries idempotent
    merged_into      BIGINT REFERENCES tickets(id),
    root_cause       TEXT,
    resolution       TEXT,
    created_by       TEXT NOT NULL,
    created_at       TEXT NOT NULL,
    acknowledged_at  TEXT,
    acknowledged_by  TEXT,
    resolved_at      TEXT,
    closed_at        TEXT,
    updated_at       TEXT NOT NULL,
    revision         INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX tickets_by_event ON tickets (event_id, status);
CREATE INDEX tickets_by_status ON tickets (status, severity);

-- The audit trail: every change and comment. visibility 'reporter' means it was
-- also sent to the reporter through the bot.
CREATE TABLE ticket_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,  -- created, field, assign, status, acknowledge, comment, merge
    field       TEXT,
    old         TEXT,
    new         TEXT,
    body        TEXT,
    visibility  TEXT NOT NULL DEFAULT 'internal' CHECK (visibility IN ('internal', 'reporter')),
    "user"      TEXT NOT NULL,
    at          TEXT NOT NULL
);
CREATE INDEX ticket_activity_by_ticket ON ticket_activity (ticket_id, id);

-- Updates for the WhatsApp bot, delivered (and retried) by the outbox worker.
CREATE TABLE ticket_outbox (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    payload     TEXT NOT NULL,
    status      TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
    attempts    INTEGER NOT NULL DEFAULT 0,
    next_try_at TEXT NOT NULL,
    last_error  TEXT,
    created_at  TEXT NOT NULL,
    sent_at     TEXT
);
CREATE INDEX ticket_outbox_pending ON ticket_outbox (status, next_try_at);

CREATE TABLE helpdesk_settings (
    key    TEXT PRIMARY KEY,
    value  TEXT
);

-- --- ICT requests ------------------------------------------------------------------------------

CREATE TABLE request_links (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    team           TEXT NOT NULL,
    token          TEXT NOT NULL UNIQUE,
    created_by     TEXT NOT NULL,
    created_at     TEXT NOT NULL,
    revoked_at     TEXT,
    contact_email  TEXT  -- the team contact: gets the link and the deadline reminders
);

CREATE TABLE request_settings (
    document_id   BIGINT PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE,
    deadline      TEXT,   -- YYYY-MM-DD: requests after this day are flagged late
    instructions  TEXT
);

CREATE TABLE ict_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id        BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    link_id            BIGINT REFERENCES request_links(id) ON DELETE SET NULL,
    batch              TEXT NOT NULL,  -- lines submitted together
    team               TEXT NOT NULL,
    kind               TEXT NOT NULL CHECK (kind IN ('wired', 'wifi')),
    status             TEXT NOT NULL CHECK (status IN ('submitted', 'needs_info', 'approved', 'declined')),
    requester_name     TEXT NOT NULL,
    requester_contact  TEXT NOT NULL,
    data               TEXT NOT NULL,
    late               INTEGER NOT NULL DEFAULT 0,
    submitted_at       TEXT NOT NULL,
    reviewed_by        TEXT,
    reviewed_at        TEXT,
    review_note        TEXT,
    record_id          BIGINT,  -- the Ethernet/Wi-Fi row created on approval
    revision           INTEGER NOT NULL DEFAULT 1,
    updated_at         TEXT NOT NULL
);
CREATE INDEX ict_requests_by_doc ON ict_requests (document_id, status);

-- --- notifications -----------------------------------------------------------------------------

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        TEXT NOT NULL,
    severity    TEXT NOT NULL CHECK (severity IN ('urgent', 'normal', 'low')),
    title       TEXT NOT NULL,
    body        TEXT,
    link        TEXT,
    audience    TEXT NOT NULL,
    event_id    BIGINT REFERENCES documents(id) ON DELETE SET NULL,
    dedup_key   TEXT UNIQUE,
    created_at  TEXT NOT NULL
);
CREATE INDEX notifications_by_audience ON notifications (audience, id);

CREATE TABLE notification_reads (
    notification_id  BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    "user"           TEXT NOT NULL,
    read_at          TEXT NOT NULL,
    PRIMARY KEY (notification_id, "user")
);

CREATE TABLE notification_prefs (
    "user"      TEXT PRIMARY KEY,
    push_types  TEXT NOT NULL  -- JSON list of PUSH_TYPES keys
);

CREATE TABLE push_subscriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user"      TEXT NOT NULL,
    role        TEXT NOT NULL,
    endpoint    TEXT NOT NULL UNIQUE,
    p256dh      TEXT NOT NULL,
    auth        TEXT NOT NULL,
    created_at  TEXT NOT NULL
);

CREATE TABLE notification_deliveries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id  BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    channel          TEXT NOT NULL CHECK (channel IN ('push', 'slack', 'email')),
    target           TEXT NOT NULL,  -- subscription id, 'channel', or an email address
    status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
    attempts         INTEGER NOT NULL DEFAULT 0,
    next_try_at      TEXT NOT NULL,
    last_error       TEXT,
    created_at       TEXT NOT NULL,
    sent_at          TEXT
);
CREATE INDEX notification_deliveries_due ON notification_deliveries (status, next_try_at);

-- People emailed when a version of the event is published (contractors, venue, ICT).
CREATE TABLE event_watchers (
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    email        TEXT NOT NULL,
    created_by   TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    PRIMARY KEY (document_id, email)
);
"""

TABLES = (  # dependents first, so each can be dropped
    "event_watchers", "notification_deliveries", "push_subscriptions", "notification_prefs", "notification_reads",
    "notifications", "ict_requests", "request_settings", "request_links", "helpdesk_settings", "ticket_outbox",
    "ticket_activity", "tickets", "comments", "workbook_snapshots", "published_snapshots", "change_log", "records",
    "event_lists", "event_groups", "event_venues", "download_log", "document_versions", "documents",
)


def upgrade() -> None:
    op.execute(SCHEMA)


def downgrade() -> None:
    for table in TABLES:
        op.execute(f"DROP TABLE {table}")
